import { Router, Request, Response } from 'express';
import { 
  getDatabase, 
  getAllReports, 
  getReportById, 
  insertReport, 
  updateReportStatus, 
  incrementUpvote, 
  getReportStats 
} from '../db/database.js';
import { analyzeCivicIssue } from '../ai/service.js';
import { validateReportInput, aiRateLimiter, validateDemoAdmin } from '../middleware/validation.js';
import { CivicReport, ReportStatus, IssueCategory, PriorityLevel } from '../types.js';

const router = Router();

// GET /api/system/health - Health check and system diagnostic info
router.get('/system/health', async (_req: Request, res: Response) => {
  try {
    const db = await getDatabase();
    res.json({
      status: 'operational',
      appName: 'CivicLens AI',
      edition: 'Hacktoberfest Hack Day Lucknow — Open Source Edition',
      llmProvider: process.env.LLM_PROVIDER || 'gemini',
      llmModel: process.env.LLM_MODEL || 'gemini-3.8-flash',
      database: 'SQLite (WebAssembly & Local Storage)',
      timestamp: new Date().toISOString()
    });
  } catch (err: any) {
    res.status(500).json({ status: 'degraded', error: err.message });
  }
});

// GET /api/reports/stats - Aggregate stats for dashboard
router.get('/reports/stats', async (_req: Request, res: Response) => {
  try {
    const db = await getDatabase();
    const stats = getReportStats(db);
    res.json({ success: true, stats });
  } catch (err: any) {
    console.error('[API] Error fetching report stats:', err);
    res.status(500).json({ error: 'Failed to calculate report statistics' });
  }
});

// GET /api/reports - List reports with filtering and search
router.get('/reports', async (req: Request, res: Response) => {
  try {
    const db = await getDatabase();
    const { search, category, priority, status } = req.query;

    const reports = getAllReports(db, {
      search: typeof search === 'string' ? search : undefined,
      category: typeof category === 'string' ? category : undefined,
      priority: typeof priority === 'string' ? priority : undefined,
      status: typeof status === 'string' ? status : undefined
    });

    res.json({ success: true, reports, count: reports.length });
  } catch (err: any) {
    console.error('[API] Error listing reports:', err);
    res.status(500).json({ error: 'Failed to retrieve reports from database' });
  }
});

// GET /api/reports/:id - Fetch individual report
router.get('/reports/:id', async (req: Request, res: Response) => {
  try {
    const db = await getDatabase();
    const report = getReportById(db, req.params.id);

    if (!report) {
      return res.status(404).json({ error: 'Report not found with the specified ID' });
    }

    res.json({ success: true, report });
  } catch (err: any) {
    console.error('[API] Error fetching report by ID:', err);
    res.status(500).json({ error: 'Failed to fetch report details' });
  }
});

// POST /api/reports/analyze - Perform AI analysis without saving
router.post('/reports/analyze', aiRateLimiter, validateReportInput, async (req: Request, res: Response) => {
  try {
    const { title, description, location, imageData } = req.body;

    const analysis = await analyzeCivicIssue({
      title: title.trim(),
      description: description.trim(),
      location: location.trim(),
      imageData
    });

    res.json({
      success: true,
      analysis,
      disclaimer: 'AI priority and category are recommendations generated by open-source inference models to aid rapid triage, not legally binding assessments.'
    });
  } catch (err: any) {
    console.error('[API] Error during AI analysis:', err);
    res.status(500).json({
      error: 'AI analysis encountered an unexpected issue',
      message: err.message
    });
  }
});

// POST /api/reports - Create and persist a new report
router.post('/reports', validateReportInput, async (req: Request, res: Response) => {
  try {
    const db = await getDatabase();
    const {
      title,
      description,
      location,
      imageData,
      citizenContact,
      editedDraft,
      customCategory,
      customPriority,
      precomputedAnalysis
    } = req.body;

    // Use precomputed analysis if passed from user preview, or run analysis now
    let analysis = precomputedAnalysis;
    if (!analysis) {
      analysis = await analyzeCivicIssue({
        title: title.trim(),
        description: description.trim(),
        location: location.trim(),
        imageData
      });
    }

    // Generate unique ID: e.g. LKO-2026-XXXX
    const randomSuffix = Math.floor(1000 + Math.random() * 9000);
    const reportId = `LKO-2026-${randomSuffix}`;
    const now = new Date().toISOString();

    const newReport: CivicReport = {
      id: reportId,
      title: title.trim(),
      description: description.trim(),
      location: location.trim(),
      category: (customCategory as IssueCategory) || analysis.category,
      department: analysis.department || 'Lucknow Nagar Nigam',
      priority: (customPriority as PriorityLevel) || analysis.priority,
      priorityReason: analysis.priorityReason,
      summary: analysis.summary,
      missingInformation: analysis.missingInformation || [],
      recommendedSteps: analysis.recommendedSteps || [],
      complaintDraft: editedDraft?.trim() || analysis.complaintDraft,
      imageData: imageData || undefined,
      status: 'Reported',
      statusHistory: [
        {
          status: 'Reported',
          timestamp: now,
          note: 'Civic grievance officially registered through CivicLens AI portal.',
          updatedBy: 'Citizen Reporter'
        }
      ],
      upvotes: 1,
      citizenContact: citizenContact?.trim() || undefined,
      aiConfidence: analysis.confidenceScore || 0.85,
      modelUsed: analysis.modelUsed || process.env.LLM_MODEL || 'gemini-3.8-flash',
      createdAt: now,
      updatedAt: now
    };

    insertReport(db, newReport);

    res.status(201).json({
      success: true,
      report: newReport,
      message: 'Report successfully stored in SQLite database.'
    });
  } catch (err: any) {
    console.error('[API] Error creating report:', err);
    res.status(500).json({ error: 'Failed to create report', message: err.message });
  }
});

// PATCH /api/reports/:id/status - Update report status (Demonstration Admin)
router.patch('/reports/:id/status', validateDemoAdmin, async (req: Request, res: Response) => {
  try {
    const { status, note, updatedBy } = req.body;
    const validStatuses: ReportStatus[] = ['Reported', 'Under Review', 'Action In Progress', 'Resolved', 'Dismissed'];

    if (!validStatuses.includes(status)) {
      return res.status(400).json({
        error: 'Invalid status',
        message: `Status must be one of: ${validStatuses.join(', ')}`
      });
    }

    const db = await getDatabase();
    const updated = updateReportStatus(
      db, 
      req.params.id, 
      status, 
      note || `Status updated to ${status}`, 
      updatedBy || 'Demonstration Admin'
    );

    if (!updated) {
      return res.status(404).json({ error: 'Report not found' });
    }

    res.json({
      success: true,
      report: updated,
      message: `Report status updated to "${status}".`
    });
  } catch (err: any) {
    console.error('[API] Error updating status:', err);
    res.status(500).json({ error: 'Failed to update report status' });
  }
});

// POST /api/reports/:id/upvote - Upvote a report to show community solidarity
router.post('/reports/:id/upvote', async (req: Request, res: Response) => {
  try {
    const db = await getDatabase();
    const upvotes = incrementUpvote(db, req.params.id);

    if (upvotes === null) {
      return res.status(404).json({ error: 'Report not found' });
    }

    res.json({ success: true, upvotes });
  } catch (err: any) {
    console.error('[API] Error incrementing upvote:', err);
    res.status(500).json({ error: 'Failed to upvote report' });
  }
});

export default router;
